// Package web implements the mineserver-manager API server: it serves the
// embedded React UI and a JSON API (/api/*) to manage server instances.
// All filesystem access is confined to the configured api home folder
// (see Sandbox).
package web

import (
	"embed"
	"encoding/json"
	"fmt"
	"io/fs"
	"log/slog"
	"net/http"
	"strings"

	cfg "github.com/eldius/mineserver-manager/internal/config"
	"github.com/eldius/mineserver-manager/internal/repository"
	"go.opentelemetry.io/contrib/instrumentation/net/http/otelhttp"
)

// staticFiles holds the React build output (internal/web/static,
// generated by `npm --prefix internal/web/ui run build`).
//
//go:embed all:static
var staticFiles embed.FS

// StartApi starts the API server on the given port.
func StartApi(port int) error {
	sb, err := NewSandbox(cfg.GetApiHomePath())
	if err != nil {
		return err
	}

	// Persistence is best-effort, like in the CLI: the API still serves
	// the UI and version endpoints without it.
	var repo repository.Repository
	if rp, err := repository.NewStormRepository(cfg.GetAppHomePath()); err != nil {
		slog.With("error", err).Warn("failed to open instance repository; instance endpoints will be unavailable")
	} else {
		repo = rp
	}

	auth := newAuthenticator(cfg.GetApiAuthPassword(), cfg.GetApiAuthTokenTTL())
	ih := &instanceHandler{repo: repo, sb: sb}
	vh := versionsHandler{}

	api := http.NewServeMux()
	api.HandleFunc("GET /version", vh.version)
	api.HandleFunc("GET /versions", vh.list)
	api.HandleFunc("GET /instances", ih.list)
	api.HandleFunc("POST /instances", ih.install)
	api.HandleFunc("POST /instances/{id}/start", ih.start)
	api.HandleFunc("POST /instances/{id}/stop", ih.stop)
	api.HandleFunc("POST /instances/{id}/backup", ih.backup)

	mux := http.NewServeMux()
	mux.HandleFunc("POST /api/login", auth.loginHandler)
	mux.Handle("/api/", auth.middleware(http.StripPrefix("/api", api)))
	mux.Handle("/", spaHandler())

	slog.Info("starting api server", "port", port, "home", sb.Home())
	s := &http.Server{
		Addr:    fmt.Sprintf(":%d", port),
		Handler: otelhttp.NewHandler(mux, "mineserver-manager-api"),
	}
	return s.ListenAndServe()
}

// spaHandler serves the embedded React build, falling back to index.html
// for unknown paths so client-side routing works.
func spaHandler() http.Handler {
	sub, err := fs.Sub(staticFiles, "static")
	if err != nil {
		// static is embedded at compile time; this can only fail if the
		// embed pattern above stops matching the build output.
		panic(fmt.Errorf("loading embedded static files: %w", err))
	}
	fileServer := http.FileServerFS(sub)
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		p := strings.TrimPrefix(r.URL.Path, "/")
		if p != "" {
			if st, err := fs.Stat(sub, p); err == nil && !st.IsDir() {
				fileServer.ServeHTTP(w, r)
				return
			}
		}
		http.ServeFileFS(w, r, sub, "index.html")
	})
}

func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}

func writeError(w http.ResponseWriter, status int, msg string) {
	writeJSON(w, status, map[string]string{"error": msg})
}
